import { capabilityDocument } from '@nextgen/core-capability';
import { normalize } from './text.ts';
import { buildEnumIndex } from './slots.ts';
import { actionVocabularyOf } from './action.ts';
import type { Capability, EnumIndex, Registry, RegistryFile, Vector } from './types.ts';

/**
 * Build a `Registry` from data that is already in memory (WP-24).
 *
 * `loadRegistry` reads a file with `readFileSync` and fits an embedder over the
 * corpus — both fine on a server, and neither available in a browser. This is
 * the same construction with **no I/O, no embedder and no network**: hand it the
 * parsed registry and the vectors that shipped beside it, and stages 1 and 2 are
 * ready.
 *
 * ## Why the vectors ship rather than being computed on load
 *
 * They *could* be computed: the zero-dependency encoder is pure arithmetic and
 * needs nothing external. Shipping them instead buys two things.
 *
 * **The fit is not free.** Fitting TF-IDF over 145 documents means building a
 * vocabulary of ~8,400 terms and an IDF table before the first turn can be
 * routed. Doing it at startup puts that on the critical path of the first
 * question a user asks.
 *
 * **And it removes a way to be wrong.** A fitted vocabulary is *state*: the
 * vectors mean nothing except relative to the corpus they were fitted on.
 * Shipping the vectors means the ranking a user gets is the ranking that was
 * measured, rather than one reproduced from the same inputs and hopefully the
 * same code. Lessons L10 is what happens when that assumption is wrong and
 * nobody checks — an embedder re-fitted between building an index and querying
 * it produced a twelvefold error that stood as a headline finding.
 *
 * ## What this does NOT do
 *
 * It does not check that the vectors match the documents. It cannot: a vector is
 * opaque. `indexEncoder` and `indexSchemaVersion` are recorded so a caller can
 * refuse a mismatch, and `assertIndexMatches` below does exactly that — but a
 * stale index built from the *same* encoder and schema over *different* text is
 * indistinguishable from a good one. That is what the build-time staleness gate
 * is for, and it is the reason the index is generated by the same
 * `capabilityDocument` the router would have used.
 */
export interface ShippedIndex {
  readonly schemaVersion: number;
  readonly encoder: string;
  readonly generatedAt: string;
  readonly entries: readonly { readonly capabilityId: string; readonly vector: readonly number[] }[];
}

export class IndexMismatchError extends Error {
  constructor(reason: string) {
    super(
      `shipped embedding index does not match this registry: ${reason}. ` +
        'Routing against a mismatched index produces confident nonsense rather ' +
        'than an error, so this refuses to start instead.',
    );
    this.name = 'IndexMismatchError';
  }
}

/**
 * Refuse an index that cannot belong to this registry.
 *
 * Deliberately strict about **order and membership**, because the runtime pairs
 * `capabilities[i]` with `vectors[i]` positionally. An index with the right ids
 * in the wrong order would route every question to the wrong screen, with full
 * confidence and no symptom.
 */
export function assertIndexMatches(registry: RegistryFile, index: ShippedIndex): void {
  if (index.schemaVersion !== registry.schemaVersion) {
    throw new IndexMismatchError(
      `schema ${index.schemaVersion} against registry schema ${registry.schemaVersion}`,
    );
  }
  if (index.entries.length !== registry.capabilities.length) {
    throw new IndexMismatchError(
      `${index.entries.length} vectors for ${registry.capabilities.length} capabilities`,
    );
  }
  for (const [i, cap] of registry.capabilities.entries()) {
    const entry = index.entries[i];
    if (entry?.capabilityId !== cap.id) {
      throw new IndexMismatchError(
        `entry ${i} is "${entry?.capabilityId ?? 'missing'}" where the registry has "${cap.id}"`,
      );
    }
  }
  const width = index.entries[0]?.vector.length;
  if (width !== undefined && index.entries.some((e) => e.vector.length !== width)) {
    throw new IndexMismatchError('vectors are not all the same width');
  }
}

/**
 * The browser entry point: a routable registry, synchronously, from data alone.
 *
 * Synchronous on purpose — there is nothing to await, and an `async` signature
 * would invite a caller to believe otherwise.
 */
export function registryFromIndex(raw: RegistryFile, index: ShippedIndex): Registry {
  assertIndexMatches(raw, index);

  const enums: Record<string, EnumIndex> = {};
  for (const [name, def] of Object.entries(raw.enums ?? {})) {
    enums[name] = buildEnumIndex(def);
  }

  const capabilities = raw.capabilities;

  const triggerIndex = new Map<string, string>();
  for (const cap of capabilities) {
    for (const trigger of cap.triggers ?? []) {
      const key = normalize(trigger);
      if (triggerIndex.has(key) && triggerIndex.get(key) !== cap.id) {
        console.warn(`[registry] trigger collision on "${key}": ${triggerIndex.get(key)} vs ${cap.id}`);
      }
      triggerIndex.set(key, cap.id);
    }
  }

  return {
    schemaVersion: raw.schemaVersion,
    domainDescription: raw.domainDescription,
    ...(raw.context ? { context: raw.context } : {}),
    capabilities,
    byId: new Map<string, Capability>(capabilities.map((c) => [c.id, c])),
    triggerIndex,
    // Recomputed rather than shipped: it is a pure function of text the registry
    // already carries, so shipping it would be bytes that can disagree with
    // themselves. The vectors are shipped precisely because they *cannot* be
    // derived without the fitted corpus.
    documents: capabilities.map(capabilityDocument),
    vectors: index.entries.map((e) => e.vector as Vector),
    enums,
    boundaryIds: new Set(capabilities.filter((c) => c.kind === 'unsupported').map((c) => c.id)),
    actionVocabulary: actionVocabularyOf(capabilities.filter((c) => c.kind !== 'unsupported')),
  };
}
